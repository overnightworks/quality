def agent_runtime_requirements() -> str:
    """The shape of agent-runtime's tests/keycloak/requirements.txt: 25 hashed pins and one direct-URL wheel, 26 in all."""
    pins = "".join(f"# via package-{number}\npackage-{number}==1.{number} \\\n    {HASH} \\\n    {HASH}\n" for number in range(25))
    return f"# generated by uv pip compile\n{pins}{WEBAUTH_WHEEL}\n"


